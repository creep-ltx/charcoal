#!/usr/bin/env bash
# Builds widetab.go: the characters a terminal shows two columns wide (East
# Asian Width W or F) as ranges, from the Unicode Character Database.
# Charcoal's own table, not Go's: the standard library has none, and Go's
# Unicode version changes with the toolchain (docs/wide-design.md).
#   tools/widetab.sh [version]      (default 17.0.0; run from the repository)
set -euo pipefail
ver=${1:-17.0.0}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -sSfL -o "$tmp/eaw.txt" "https://www.unicode.org/Public/$ver/ucd/EastAsianWidth.txt"
{
  echo "// Code generated by tools/widetab.sh from EastAsianWidth-$ver.txt; DO NOT EDIT."
  echo
  echo "package main"
  echo
  echo "// uniWideVersion is the Unicode version of uniWideRanges."
  echo "const uniWideVersion = \"$ver\""
  echo
  echo "// uniWideRanges are the characters of East Asian Width W or F, first and last, in order."
  echo "var uniWideRanges = [...][2]rune{"
  sed -e 's/#.*//' "$tmp/eaw.txt" | awk -F';' '
    NF >= 2 {
      gsub(/[ \t]/, "", $1); gsub(/[ \t]/, "", $2)
      if ($2 != "W" && $2 != "F") next
      n = split($1, r, /\.\./)
      a = strtonum("0x" r[1]); b = (n > 1) ? strtonum("0x" r[2]) : a
      if (have && a == last + 1) { last = b; next }
      if (have) printf "\t{0x%04X, 0x%04X},\n", first, last
      first = a; last = b; have = 1
    }
    END { if (have) printf "\t{0x%04X, 0x%04X},\n", first, last }'
  echo "}"
} > widetab.go
gofmt -l widetab.go >/dev/null
echo "widetab.go: $(grep -c '^	{0x' widetab.go) ranges (Unicode $ver)"
