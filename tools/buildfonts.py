#!/usr/bin/env python3
"""Pack the 8x16 bitmap fonts into app/fonts.js.

Every font is 256 glyphs of 16 bytes (bit 7 = the left pixel), indexed by the
byte in the file: Latin-1 for the Amiga fonts, CP437 for the IBM VGA font.
The Amiga fonts are TrueSchool's raw conversions (8x8 with every row doubled).
The VGA font is rendered from the Px437 TrueType font at its native 16 px.
Needs Pillow only for the VGA font.
"""
import base64
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, '..', 'fonts')
OUT = os.path.join(HERE, '..', 'app', 'fonts.js')

# id, name shown, file, SAUCE font name (TInfoS), SyncTERM font number
AMIGA = [
    ('topaz1',  'Topaz 1 (A500)',      'Topaz_a500_v1.0.raw',       'Amiga Topaz 1',     42),
    ('topaz1p', 'Topaz 1+ (A500)',     'TopazPlus_a500_v1.0.raw',   'Amiga Topaz 1+',    40),
    ('topaz2',  'Topaz 2 (A1200)',     'Topaz_a1200_v1.0.raw',      'Amiga Topaz 2',     None),
    ('topaz2p', 'Topaz 2+ (A1200)',    'TopazPlus_a1200_v1.0.raw',  'Amiga Topaz 2+',    None),
    ('mk',      'MicroKnight',         'MicroKnight_v1.0.raw',      'Amiga MicroKnight', 41),
    ('mkp',     'MicroKnight+',        'MicroKnightPlus_v1.0.raw',  'Amiga MicroKnight+', 39),
    ('noodle',  'P0T-NOoDLE',          'P0T-NOoDLE_v1.0.raw',       'Amiga P0T-NOoDLE',  37),
    ('mosoul',  "mO'sOul",             "mO'sOul_v1.0.raw",          'Amiga mOsOul',      38),
]

# CP437 0x00-0x1F and 0x7F as glyphs (the codec gives control characters).
CP437_LOW = ('\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼')


def cp437_char(b):
    if b < 32:
        return CP437_LOW[b]
    if b == 0x7F:
        return '⌂'
    return bytes([b]).decode('cp437')


def render_vga():
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(os.path.join(FONTS, 'Px437_IBM_VGA_8x16.ttf'), 16)
    out = bytearray()
    for b in range(256):
        img = Image.new('L', (8, 16), 0)
        if b not in (0, 0x20, 0xFF):
            ImageDraw.Draw(img).text((0, 0), cp437_char(b), font=font, fill=255)
        px = img.load()
        for y in range(16):
            row = 0
            for x in range(8):
                if px[x, y] >= 128:
                    row |= 0x80 >> x
            out.append(row)
    return bytes(out)


def main():
    lines = ['// Generated by tools/buildfonts.py - do not edit.',
             '// Amiga fonts: TrueSchool "Multi Platform Amiga Fonts" (dMG/t!s^dS!, GPL-FE).',
             '// IBM VGA: Px437_IBM_VGA_8x16 from "The Ultimate Oldschool PC Font Pack" (VileR, CC BY-SA 4.0).',
             'const FONT_DATA = [']
    for fid, name, fn, sauce, sync in AMIGA:
        data = open(os.path.join(FONTS, fn), 'rb').read()
        assert len(data) == 4096, fn
        lines.append('  {id:%r, name:%r, kind:"amiga", sauce:%r, syncterm:%s, b64:"%s"},' % (
            fid, name, sauce, 'null' if sync is None else sync, base64.b64encode(data).decode()))
    vga = render_vga()
    lines.append('  {id:"vga", name:"IBM VGA (CP437)", kind:"pc", sauce:"IBM VGA", syncterm:0, b64:"%s"},'
                 % base64.b64encode(vga).decode())
    lines.append('];')
    # CP437 byte -> Unicode, for typing on a PC page and for UTF-8 export.
    table = ''.join(cp437_char(b) if b else ' ' for b in range(256))
    lines.append('const CP437_UNICODE = %s;' % repr_js(table))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(OUT))


def repr_js(s):
    return '"' + ''.join(c if (c not in '"\\' and ord(c) >= 32) else '\\u%04x' % ord(c) for c in s) + '"'


if __name__ == '__main__':
    sys.exit(main())
