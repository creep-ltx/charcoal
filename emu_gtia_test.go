func TestEmuAltirraPalette(t *testing.T) {
	for v, want := range emuFAltirraPAL {
		if got := gtiaPAL[v] & 0xFFFFFF; got != want {
			t.Errorf("colour $%02X: %06X, Altirra's %06X", v, got, want)
		}
	}
	if gtiaPAL[0x94]&0xFFFFFF != 0x005F8A || gtiaPAL[0x0E]&0xFFFFFF != 0xEEEEEE {
		t.Fatal("the start-up blue or grey 14")
	}
	// The default palette is Altirra's PAL; atari800's stay as choices, and the
	// old ids still name a GTIA palette.
	a := testApp(t, "atari")
	if a.atariRGB(0x94) != gtiaPAL[0x94] || a.pal != atariPalette.colors {
		t.Fatal("a new Atari page is not on Altirra's PAL")
	}
	for id, tab := range map[string]*[256]uint32{"atari": &gtiaPAL, "atarintsc": &gtiaNTSC, "atari800pal": &gtia800PAL, "atarintscalt": &gtiaAltNTSC} {
		a.paletteFor["atari"] = id
		a.setPalette()
		if a.atariRGB(0x94) != tab[0x94] || !isGTIAPalette(paletteByID(id)) {
			t.Fatalf("palette %s", id)
		}
	}
	// Altirra's NTSC: the start-up blue is a blue, greys rise and are nearly
	// grey (its NTSC primaries have illuminant C's white, so sRGB greys tint).
	if c := gtiaAltNTSC[0x94]; c&255 <= c>>16&255 {
		t.Fatalf("NTSC $94 is %06X", c&0xFFFFFF)
	}
	for l := 2; l < 16; l += 2 {
		c, p := gtiaAltNTSC[l], gtiaAltNTSC[l-2]
		if emuFRGBDist(c, c&255*0x010101) > int(c&255)/12+2 || c&255 <= p&255 {
			t.Fatalf("NTSC grey %d: %06X", l, c&0xFFFFFF)
		}
	}
}
